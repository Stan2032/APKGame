package io.github.stan2032.gravitygambit.core

/**
 * Expedition — a run of chained systems (docs/VISION.md §3.6, Stage D).
 *
 * The campaign is a list. You can put it down after any level and lose
 * nothing, which is exactly what makes it a good teacher and a poor reason to
 * open the app again. A run is the opposite: it has a *state you can lose*,
 * so the decision to fire one more shot costs something.
 *
 * **Additive, not a replacement** (D-32b). VISION originally had Expedition
 * replacing the sector grid; the owner's call is that the campaign stays.
 * That decision shapes this file more than any other: a leg is played as an
 * ordinary [GameMode.CAMPAIGN] match, generated by the same generator with
 * the same proofs, and Expedition is the *state carried between* those
 * matches. Nothing here reaches [MatchEngine], [ShareCodec] or the
 * determinism contract, so adding a run mode cost the replay protocol
 * nothing and left D-27 (objectives are campaign-only) true by construction —
 * an Expedition leg *is* a campaign match, so it is entitled to objectives.
 *
 * ### Fuel is the run
 *
 * One resource, not three. Hull and cargo would each need their own rules,
 * their own UI and their own failure state to earn their place, and a player
 * cannot hold three trend lines in their head between shots.
 *
 * Fuel leaves in two ways and returns in one:
 *
 * - **Travel** to the next system costs [travelCost], which grows with depth.
 * - **Each shot** costs [shotCost] — flat, so a shot is always the same small
 *   decision.
 * - **Clearing** a system refunds fuel, more for the harder route and more
 *   for shooting well.
 *
 * ### Why runs provably end
 *
 * The first draft put all the escalation on the shot cost, and the test for
 * it failed immediately — and taught the design. A per-shot cost cannot clock
 * a player who fires *one* shot, so a perfect player ran to the leg cap with
 * a full tank and Expedition was an idle game with extra steps.
 *
 * Travel cost fixes it structurally rather than by tuning. Refunds are
 * bounded above by [MAX_REFUND]; travel cost rises without bound. So past
 * [BLEED_DEPTH] **every leg is a net loss no matter how perfectly it is
 * played**, fuel strictly decreases, and the run ends. That is an argument
 * from arithmetic, not a hope that the difficulty curve outruns the player —
 * and `runsAlwaysEnd` checks it against the best player the rules permit
 * rather than against an expected one.
 *
 * The consequence worth having: as travel eats the surplus, the margin
 * between a two-shot clear and a four-shot clear stops being pocket change
 * and starts being the run. Shooting well does not merely score better; deep
 * enough, it is the difference between continuing and not.
 */
object Expedition {

    /** Enough to survive several bad opening legs, not enough to coast. */
    const val START_FUEL = 16

    /** Flat: a shot is always the same small decision. Escalation lives in [travelCost]. */
    const val SHOT_COST = 1

    /** Difficulty of leg 0 before any route modifier. */
    const val BASE_DIFFICULTY = 2

    /** How many legs deep before the base difficulty rises by one. */
    const val DIFFICULTY_STEP_LEGS = 2

    /** A hard ceiling on the chain, so state and UI are bounded. Nobody is expected to reach it. */
    const val MAX_LEGS = 40

    /** Fuel returned for a clear, before route and star bonuses. */
    const val CLEAR_REFUND = 3

    /** Extra fuel per star above one — the whole reason to shoot well rather than merely win. */
    const val FUEL_PER_EXTRA_STAR = 2

    /**
     * The most fuel any single clear can return: the richest route
     * ([Route.UNKNOWN] pays 4 and is the only route that can roll
     * [Mutator.WINDFALL], which doubles it), three stars, everything going
     * right. Derived from the table rather than typed in, so it cannot fall
     * out of step with it — and `runsAlwaysEnd` leans on it being true.
     */
    val MAX_REFUND: Int =
        2 * (CLEAR_REFUND + Route.UNKNOWN.fuelReward + FUEL_PER_EXTRA_STAR * 2)

    /**
     * The depth past which travel alone costs more than the best possible
     * clear returns. Every leg beyond this is a net loss however well it is
     * played, which is what makes the run finite.
     */
    val BLEED_DEPTH: Int = MAX_REFUND

    /**
     * A route offered at a junction.
     *
     * Three flavours rather than a spread of numbers, because the choice has
     * to be readable in the two seconds between systems.
     */
    enum class Route(
        val id: Int,
        val label: String,
        val brief: String,
        /** Added to the leg's base difficulty. */
        val difficultyDelta: Int,
        /** Fuel returned on top of [CLEAR_REFUND] when the system is cleared. */
        val fuelReward: Int,
    ) {
        SAFE(0, "The quiet way", "Easier system, less fuel", -1, 2),
        RICH(1, "The deep way", "Harder system, more fuel", 2, 6),

        /**
         * Same difficulty as the base, a middling reward, and a [Mutator] —
         * so "unknown" names something real rather than being a third number.
         */
        UNKNOWN(2, "Uncharted", "Unchanged odds, and a condition", 0, 4);

        companion object {
            fun byId(id: Int): Route = entries.firstOrNull { it.id == id } ?: SAFE
        }
    }

    /**
     * A condition attached to an Uncharted route, lasting one leg.
     *
     * Every one of these is a **rule** the run applies to itself, never a
     * request to the generator. That is deliberate: a mutator like "binary
     * star ahead" would have to ask the generator for a layout it may not be
     * able to produce in band, and the generator's fallback would then leave
     * the run quietly claiming a condition that never applied — the failure
     * mode D-24 and D-27 exist to prevent. Field-shaping mutators are worth
     * having and are deferred until the generator can *prove* one took.
     */
    enum class Mutator(val id: Int, val displayName: String, val brief: String) {
        NONE(0, "Clear skies", "Nothing unusual"),

        /**
         * No aim preview for this leg.
         *
         * This is D-23's *Blind* finding a home. Blind was cut from Gambits
         * because nothing in a `TurnInput` records whether the sender looked
         * at their preview, so a peer re-simulating a duel would have to take
         * the claim on trust — a scoring rule that only works if everyone is
         * honest. That objection is about **verification by a stranger**, and
         * it simply does not apply here: a run is solo, nothing is sent, and
         * the only person the condition binds is the one who chose it. The
         * idea was always good; it was the *scoring* that was unverifiable.
         */
        BLIND(1, "Dark run", "No aim trace on this system"),

        /** Every shot on this leg costs one extra fuel. */
        VOLATILE(2, "Thin reserves", "Each shot costs 1 more fuel"),

        /** Double the route's fuel reward — Uncharted must be able to pay, not only to charge. */
        WINDFALL(3, "Rich seam", "Double fuel for clearing this system");

        companion object {
            fun byId(id: Int): Mutator = entries.firstOrNull { it.id == id } ?: NONE
        }
    }

    /** One offer at a junction: where it goes, what it pays, and what it demands. */
    data class Leg(
        val route: Route,
        val mutator: Mutator,
        val difficulty: Int,
        /** The seed the system is generated from — fixed at offer time, so the choice is honest. */
        val seed: Long,
    )

    /**
     * The whole run, as a value.
     *
     * Immutable with pure transitions, so a run can be replayed from its seed
     * and choices, and so nothing about it can drift while a match is on
     * screen.
     */
    data class Run(
        val seed: Long,
        /** Legs cleared. Also the index of the leg now being offered. */
        val depth: Int = 0,
        val fuel: Int = START_FUEL,
        val score: Int = 0,
        val starsEarned: Int = 0,
        /** Legs entered and not cleared. Costs fuel, never ends the run by itself. */
        val wrecks: Int = 0,
    ) {
        /**
         * A run is over when it cannot pay to reach the next system and fire
         * once there. Stranding a player at a junction they can travel to but
         * not shoot in would be a worse ending than an honest empty tank.
         */
        val over: Boolean get() = fuel < travelCost(depth) + shotCost() || depth >= MAX_LEGS
    }

    /**
     * Fuel to reach the system at [depth]. **This is the clock on the run.**
     *
     * Linear and unbounded, against refunds that are bounded — see the class
     * note on why runs provably end. Leg 0 is free: the run starts where you
     * are.
     */
    fun travelCost(depth: Int): Int = depth

    /** Fuel for one shot under [mutator]. Flat except where a condition says otherwise. */
    fun shotCost(mutator: Mutator = Mutator.NONE): Int =
        SHOT_COST + if (mutator == Mutator.VOLATILE) 1 else 0

    /**
     * What the leg at [depth] costs before any refund: getting there, plus
     * [shots] fired. The number a player is really deciding about when they
     * take one more shot.
     */
    fun legCost(depth: Int, mutator: Mutator, shots: Int): Int =
        travelCost(depth) + shots * shotCost(mutator)

    /** Base difficulty at [depth], before the route's delta. */
    fun baseDifficulty(depth: Int): Int =
        (BASE_DIFFICULTY + depth / DIFFICULTY_STEP_LEGS).coerceAtMost(11)

    /**
     * The routes offered at [run]'s current junction: one of each flavour, so
     * the shape of the decision never changes even though its terms do.
     * Deterministic in (run seed, depth), so leaving and returning to a
     * junction cannot reroll it into something better.
     */
    fun routesFor(run: Run): List<Leg> {
        val rng = Rng(Rng.mix(run.seed, run.depth * 0x9E37L))
        return Route.entries.map { route ->
            val difficulty = (baseDifficulty(run.depth) + route.difficultyDelta).coerceIn(0, 11)
            val mutator = if (route == Route.UNKNOWN) rollMutator(rng) else Mutator.NONE
            Leg(
                route = route,
                mutator = mutator,
                difficulty = difficulty,
                seed = Seeds.expedition(run.seed, run.depth, route.id),
            )
        }
    }

    /** Uncharted always carries a real condition; [Mutator.NONE] is the absence of a mutator, not a roll. */
    private fun rollMutator(rng: Rng): Mutator {
        val real = Mutator.entries.filter { it != Mutator.NONE }
        return real[rng.nextInt(real.size)]
    }

    /** Fuel returned for clearing [leg] with [stars] (1..3). */
    fun refundFor(leg: Leg, stars: Int): Int {
        val base = CLEAR_REFUND + leg.route.fuelReward +
            FUEL_PER_EXTRA_STAR * (stars - 1).coerceAtLeast(0)
        return if (leg.mutator == Mutator.WINDFALL) base * 2 else base
    }

    /** Points for clearing [leg] with [stars]. Harder routes are worth more because they are harder. */
    fun scoreFor(leg: Leg, stars: Int): Int = 100 + 10 * leg.difficulty + 40 * stars

    /**
     * The run after clearing [leg] with [stars], having fired [shots].
     *
     * Fuel is charged for the shots actually fired and refunded for the
     * clear, so a two-shot win is worth strictly more than a four-shot win of
     * the same system — the compounding this mode exists to reward.
     */
    fun afterClear(run: Run, leg: Leg, shots: Int, stars: Int): Run {
        val spent = legCost(run.depth, leg.mutator, shots)
        return run.copy(
            depth = run.depth + 1,
            fuel = (run.fuel - spent + refundFor(leg, stars)).coerceAtLeast(0),
            score = run.score + scoreFor(leg, stars),
            starsEarned = run.starsEarned + stars,
        )
    }

    /**
     * The run after failing [leg], having fired [shots].
     *
     * A wreck advances the run rather than ending it. Ending on the first bad
     * system would make the opening minute of every run the whole game, and
     * would punish exactly the player who took the hard route — which is the
     * choice this mode wants to encourage.
     */
    fun afterWreck(run: Run, leg: Leg, shots: Int, outfits: Map<String, Int> = emptyMap()): Run {
        val spent = legCost(run.depth, leg.mutator, shots) -
            Outfitting.wreckRefund(outfits, shots, leg.mutator)
        return run.copy(
            depth = run.depth + 1,
            fuel = (run.fuel - spent).coerceAtLeast(0),
            wrecks = run.wrecks + 1,
        )
    }

    /**
     * Stardust for a finished run.
     *
     * Paid in the currency the game already has, rather than in a new one.
     * A meta-currency is only worth minting alongside the thing it buys;
     * shipping an unspendable token first would be a number that goes up and
     * means nothing (recorded in TODO as the follow-up that adds both).
     */
    fun payout(run: Run): Int = 20 + 12 * run.depth + run.score / 40

    /** The aim-preview tier permitted on [leg], overriding what the player owns. */
    /**
     * A Dark run means **no aim trace**, which is what the mutator has always
     * said and what it did not do until 0.19.0: it returned tier 0, the base
     * 90-tick preview every player owns, so the run removed a *purchase*
     * rather than the trace. `Economy.PREVIEW_NONE` is the tier that actually
     * means none.
     */
    fun previewLevelFor(leg: Leg, owned: Int): Int =
        if (leg.mutator == Mutator.BLIND) Economy.PREVIEW_NONE else owned
}
